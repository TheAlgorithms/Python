#!/bin/bash
# PreToolUse(Edit|Write): refuse edits that CONTRIBUTING.md rules out.
file=$(jq -r '.tool_input.file_path // empty')
[[ "$file" == "$CLAUDE_PROJECT_DIR"/* ]] || exit 0
rel=${file#"$CLAUDE_PROJECT_DIR"/}

case "$rel" in
    DIRECTORY.md|README.md)
        echo "$rel is autogenerated upstream (CONTRIBUTING.md line 216)" >&2; exit 2 ;;
    uv.lock)
        echo "uv.lock is regenerated by the uv-lock pre-commit hook (CONTRIBUTING.md line 205)" >&2; exit 2 ;;
    *.ipynb)
        echo "Notebooks belong in TheAlgorithms/Jupyter (CONTRIBUTING.md line 210)" >&2; exit 2 ;;
esac

if [[ "$rel" == *.py && ! -d "$(dirname "$file")" ]]; then
    echo "Avoid creating new directories; fit into the existing structure (CONTRIBUTING.md line 212)" >&2
    exit 2
fi
exit 0
